package barnacle

import (
	"embed"
	"fmt"
	"html/template"
	"io/fs"
	"net/url"
	"os"
	"path/filepath"
	"strings"
)

//go:embed assets
var assetsFS embed.FS

const markerFile = ".barnacle-site"
const markerContent = "This directory was generated by barnacle. It is safe to delete.\n"

// Generate builds the static site rooted at root and writes it into siteDir.
// root is the directory that contains the documentation (the directory the
// configuration lives in); siteDir defaults to ./site but may point anywhere,
// including outside root.
//
// It returns the number of pages written and the relative paths of every page
// that contains no Mermaid diagram, so callers can nudge (never force) users
// toward keeping a diagram at the top of each page. Missing diagrams are
// never an error.
func Generate(root, siteDir string, cfg Config) (int, []string, error) {
	rootAbs, err := filepath.Abs(root)
	if err != nil {
		return 0, nil, err
	}
	siteAbs, err := filepath.Abs(siteDir)
	if err != nil {
		return 0, nil, err
	}

	docs, err := Scan(rootAbs, siteAbs, cfg)
	if err != nil {
		return 0, nil, fmt.Errorf("scanning %s: %w", rootAbs, err)
	}
	if err := checkCollisions(docs); err != nil {
		return 0, nil, err
	}

	// Render page bodies first so we know whether Mermaid is needed.
	type page struct {
		doc     Document
		content string
	}
	pages := make([]page, 0, len(docs))
	needsMermaid := false
	var missingMermaid []string
	for _, doc := range docs {
		source, err := os.ReadFile(doc.SourcePath)
		if err != nil {
			return 0, nil, err
		}
		var content string
		renderCtx := RenderContext{SourceDir: filepath.Dir(doc.SourcePath), Root: rootAbs}
		if doc.MermaidOnly {
			content, err = MermaidPageHTML(renderCtx, doc.Title, source)
		} else {
			content, err = MarkdownToHTML(renderCtx, source)
		}
		if err != nil {
			return 0, nil, fmt.Errorf("rendering %s: %w", doc.RelPath, err)
		}
		if HasMermaid(content) {
			needsMermaid = true
		} else {
			missingMermaid = append(missingMermaid, doc.RelPath)
		}
		pages = append(pages, page{doc: doc, content: content})
	}

	if err := prepareSiteDir(siteAbs); err != nil {
		return 0, nil, err
	}
	if err := writeAssets(siteAbs, needsMermaid); err != nil {
		return 0, nil, err
	}

	tree := buildTree(docs)

	for _, p := range pages {
		nav := renderNav(tree, p.doc.OutputRel)
		out := filepath.Join(siteAbs, filepath.FromSlash(p.doc.OutputRel))
		if err := os.MkdirAll(filepath.Dir(out), 0o755); err != nil {
			return 0, nil, err
		}
		data := pageData{
			SiteTitle:  cfg.Title,
			PageTitle:  p.doc.Title,
			Content:    template.HTML(p.content),
			Nav:        template.HTML(nav),
			RelPrefix:  relPrefix(p.doc.OutputRel),
			HasMermaid: HasMermaid(p.content),
		}
		if err := renderPage(out, pageTemplate, data); err != nil {
			return 0, nil, err
		}
	}

	// Landing page.
	indexNav := renderNav(tree, "index.html")
	indexData := pageData{
		SiteTitle:  cfg.Title,
		PageTitle:  cfg.Title,
		Content:    template.HTML(renderIndex(cfg.Title, tree)),
		Nav:        template.HTML(indexNav),
		RelPrefix:  "",
		HasMermaid: false,
	}
	if err := renderPage(filepath.Join(siteAbs, "index.html"), pageTemplate, indexData); err != nil {
		return 0, nil, err
	}

	if err := os.WriteFile(filepath.Join(siteAbs, markerFile), []byte(markerContent), 0o644); err != nil {
		return 0, nil, err
	}
	return len(pages) + 1, missingMermaid, nil
}

// prepareSiteDir creates the output directory. If it already contains a
// barnacle marker file it is wiped first so stale pages disappear; an
// existing directory without the marker is left alone apart from the files
// barnacle overwrites.
func prepareSiteDir(siteAbs string) error {
	if info, err := os.Stat(siteAbs); err == nil {
		if !info.IsDir() {
			return fmt.Errorf("output path %s exists and is not a directory", siteAbs)
		}
		marker := filepath.Join(siteAbs, markerFile)
		if _, err := os.Stat(marker); err == nil {
			return os.RemoveAll(siteAbs)
		}
		return os.MkdirAll(siteAbs, 0o755)
	}
	return os.MkdirAll(siteAbs, 0o755)
}

func writeAssets(siteAbs string, includeMermaid bool) error {
	assetsDir := filepath.Join(siteAbs, "assets")
	if err := os.MkdirAll(assetsDir, 0o755); err != nil {
		return err
	}
	writes := map[string]string{
		"assets/barnacle.css": "assets/barnacle.css",
	}
	if includeMermaid {
		writes["assets/mermaid.min.js"] = "assets/mermaid.min.js"
	}
	for target, source := range writes {
		data, err := fs.ReadFile(assetsFS, source)
		if err != nil {
			return err
		}
		if err := os.WriteFile(filepath.Join(siteAbs, target), data, 0o644); err != nil {
			return err
		}
	}
	return nil
}

func checkCollisions(docs []Document) error {
	seen := map[string]string{}
	for _, doc := range docs {
		if prev, ok := seen[doc.OutputRel]; ok {
			return fmt.Errorf("documentation files %s and %s both generate %s; rename one of them", prev, doc.RelPath, doc.OutputRel)
		}
		seen[doc.OutputRel] = doc.RelPath
	}
	return nil
}

// relPrefix returns the relative path prefix from a page at outRel to the
// site root: "" for top-level pages, "../" for one level deep, and so on.
func relPrefix(outRel string) string {
	depth := strings.Count(filepath.ToSlash(outRel), "/")
	return strings.Repeat("../", depth)
}

// relativeURL returns an escaped URL for target (slash-separated, relative
// to the site root) as seen from the page at fromOutRel (slash-separated,
// relative to the site root).
func relativeURL(fromOutRel, target string) string {
	fromDir := pathDirSlash(fromOutRel)
	rel, err := filepath.Rel(filepath.FromSlash(fromDir), filepath.FromSlash(target))
	if err != nil {
		rel = target
	}
	segments := strings.Split(filepath.ToSlash(rel), "/")
	for i, segment := range segments {
		segments[i] = url.PathEscape(segment)
	}
	return strings.Join(segments, "/")
}

func pathDirSlash(p string) string {
	p = filepath.ToSlash(p)
	if i := strings.LastIndexByte(p, '/'); i >= 0 {
		return p[:i+1] // keep trailing slash so the dir is "parser/" not "parser"
	}
	return "."
}

func renderPage(path string, tmpl *template.Template, data pageData) error {
	f, err := os.Create(path)
	if err != nil {
		return err
	}
	defer f.Close()
	return tmpl.Execute(f, data)
}
