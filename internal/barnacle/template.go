package barnacle

import "html/template"

type pageData struct {
	SiteTitle    string
	PageTitle    string
	Content      template.HTML
	Nav          template.HTML
	RelPrefix    string
	HasMermaid   bool
	HasEdgeLinks bool
}

var pageTemplate = template.Must(template.New("page").Parse(`<!DOCTYPE html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<meta name="generator" content="barnacle">
<title>{{.PageTitle}}{{if ne .PageTitle .SiteTitle}} · {{.SiteTitle}}{{end}}</title>
<link rel="stylesheet" href="{{.RelPrefix}}assets/barnacle.css">
{{- if .HasMermaid}}
<script src="{{.RelPrefix}}assets/mermaid.min.js"></script>
<script>mermaid.initialize({ startOnLoad: true, securityLevel: 'strict' });</script>
{{- end}}
{{- if .HasEdgeLinks}}
<script src="{{.RelPrefix}}assets/barnacle-edges.js"></script>
{{- end}}
</head>
<body>
<aside class="sidebar">
  <a class="site-title" href="{{.RelPrefix}}index.html">{{.SiteTitle}}</a>
  <nav aria-label="Documentation">
    {{.Nav}}
  </nav>
</aside>
<main class="content">
  {{.Content}}
  <footer class="page-footer">Generated by <a href="https://github.com/fordaj/barnacle">barnacle</a></footer>
</main>
</body>
</html>
`))
