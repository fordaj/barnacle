package barnacle

import (
	"encoding/json"
	"html"
	"net/url"
	"regexp"
	"strings"
)

// Client-side search support. barnacle is a static site with no server,
// so searching happens entirely in the browser against a prebuilt index.
//
// buildSearchIndex walks the rendered pages (already produced by the
// render pipeline) and extracts, per page, its title and one section per
// heading: the heading anchor id, the heading text and the plain text of
// the body that follows it. renderSearchIndexJS serializes the result as
// an external JavaScript file that assigns window.BARNACLE_SEARCH_INDEX —
// a <script src> loads on file:// URLs, whereas fetch() of a JSON file
// does not, and barnacle sites must work opened from disk.
//
// Per-section text is capped so huge pages cannot blow up the index;
// search matches on the page blob first and then ranks sections, so the
// cap only bounds index size, not recall of typical documentation pages.

// searchSection is the searchable body of one heading section.
type searchSection struct {
	Anchor string `json:"a"`
	Title  string `json:"t"`
	Text   string `json:"x"`
}

// searchPage is one searchable page.
type searchPage struct {
	URL      string          `json:"u"` // site-root-relative URL, path-escaped ("guide/usage.html")
	Title    string          `json:"t"`
	Sections []searchSection `json:"s"`
}

const searchSectionLimit = 3000 // characters of body text kept per section

var (
	searchMermaidRe = regexp.MustCompile(`(?s)<pre class="mermaid">.*?</pre>`)
	searchSVGRe     = regexp.MustCompile(`(?s)<svg\b.*?</svg>`)
	searchScriptRe  = regexp.MustCompile(`(?s)<(script|style)\b.*?</(script|style)>`)
	searchHeadingRe = regexp.MustCompile(`(?s)<h[1-6]\b[^>]*?\bid="([^"]*)"[^>]*>(.*?)</h[1-6]>`)
	searchTagRe     = regexp.MustCompile(`(?s)<[^>]+>`)
	searchSpaceRe   = regexp.MustCompile(`\s+`)
)

// buildSearchIndex extracts the searchable content of every rendered page.
// docs and pages must correspond one-to-one (pages[i] is the HTML fragment
// rendered from docs[i]); index is returned in document order.
func buildSearchIndex(docs []Document, pages []string) []searchPage {
	index := make([]searchPage, 0, len(pages))
	for i, doc := range docs {
		index = append(index, searchPage{
			URL:      escapeOutputRel(doc.OutputRel),
			Title:    doc.Title,
			Sections: extractSections(pages[i], doc.Title),
		})
	}
	return index
}

// escapeOutputRel converts a slash- or backslash-separated output path
// into a site-root-relative URL: segments are path-escaped and joined
// with forward slashes.
func escapeOutputRel(outRel string) string {
	segments := strings.Split(strings.ReplaceAll(outRel, `\`, "/"), "/")
	for i, segment := range segments {
		segments[i] = url.PathEscape(segment)
	}
	return strings.Join(segments, "/")
}

// extractSections splits rendered HTML into heading sections and returns
// the plain text of each. The body before the first heading becomes one
// section with an empty anchor, keyed by the page title.
func extractSections(rendered, pageTitle string) []searchSection {
	text := searchMermaidRe.ReplaceAllString(rendered, " ")
	text = searchSVGRe.ReplaceAllString(text, " ")
	text = searchScriptRe.ReplaceAllString(text, " ")

	matches := searchHeadingRe.FindAllStringSubmatchIndex(text, -1)
	var sections []searchSection
	add := func(anchor, title, body string) {
		body = plainText(body)
		if title = plainText(title); title != "" || body != "" {
			if len(body) > searchSectionLimit {
				body = body[:searchSectionLimit]
			}
			sections = append(sections, searchSection{Anchor: anchor, Title: title, Text: body})
		}
	}

	if len(matches) == 0 {
		add("", pageTitle, text)
		return sections
	}
	leading := text[:matches[0][0]]
	if plainText(leading) != "" {
		add("", pageTitle, leading)
	}
	for i, loc := range matches {
		end := len(text)
		if i+1 < len(matches) {
			end = matches[i+1][0]
		}
		add(text[loc[2]:loc[3]], text[loc[4]:loc[5]], text[loc[1]:end])
	}
	return sections
}

// plainText strips tags and entities and collapses whitespace.
func plainText(s string) string {
	s = searchTagRe.ReplaceAllString(s, " ")
	s = html.UnescapeString(s)
	return strings.TrimSpace(searchSpaceRe.ReplaceAllString(s, " "))
}

// renderSearchIndexJS serializes the index as an external JavaScript
// file assigning window.BARNACLE_SEARCH_INDEX.
func renderSearchIndexJS(index []searchPage) ([]byte, error) {
	var b strings.Builder
	b.WriteString("/* Generated by barnacle. Search index for this site; do not edit. */\n")
	b.WriteString("window.BARNACLE_SEARCH_INDEX = ")
	data, err := json.Marshal(index)
	if err != nil {
		return nil, err
	}
	b.Write(data)
	b.WriteString(";\n")
	return []byte(b.String()), nil
}
